function localize(command) {
    const translated = names[command.name];

    if (translated && translated !== command.name) {
        command.name_localizations = Object.fromEntries(
            locales.map((locale) => [locale, translated]),
        );
    }

    for (const option of command.options ?? []) {
        localize(option);
    }

    return command;
}

